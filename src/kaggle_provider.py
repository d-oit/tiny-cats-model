#!/usr/bin/env python3
"""Kaggle provider adapter for the GitHub Actions control plane (ADR-067).

Packages one bounded training slice as a **private Kaggle script kernel**
(self-contained: repo ``src/``, ``data/download.py`` and
``scripts/train_kaggle.py`` plus a generated entrypoint), pushes it, polls it
to a terminal state, and writes the kernel log next to the workflow's other
artifacts.

Design constraints this encodes
-------------------------------
- HF Hub is still the only cross-provider state transport (ADR-064): the
  kernel resumes from and pushes to the Hub itself; the control plane reads
  the evidence back from the Hub (``providers.py fetch-artifacts``).
- Kaggle cannot attach secrets at push time (kaggle-api#582), so ``HF_TOKEN``
  is resolved inside the kernel from, in order: the environment, a private
  dataset mount (``/kaggle/input/<dataset>/HF_TOKEN`` — the documented
  workaround), or Kaggle Secrets when a human attached them in the UI.
- One slice must fit one GitHub Actions job (360 min): the poll deadline
  defaults to 5.5 h and the kernel session timeout to 6 h.
- The dataset is materialised by ``data/download.py`` rather than mounted, so
  the ``relpath:size`` dataset fingerprint matches the Modal slices' and the
  resume manifest gate accepts the checkpoint (ADR-063).

Exit codes
----------
``0`` kernel COMPLETE · ``2`` kernel ERROR · ``3`` kernel cancelled ·
``4`` poll deadline exceeded (logs fetched) · ``5`` config/auth/push failure.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import logging
import os
import shutil
import sys
import tempfile
import time
import zipfile
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

logger = logging.getLogger("kaggle-provider")

KERNEL_METADATA_FILE = "kernel-metadata.json"
ENTRY_FILE = "train.py"

# Copied into the kernel workspace, relative to the repo root (``src/*.py``
# is copied separately). Keeps the kernel self-contained instead of cloning.
EXTRA_KERNEL_FILES = ("data/download.py", "scripts/train_kaggle.py")

TERMINAL_OK = frozenset({"COMPLETE"})
TERMINAL_ERROR = frozenset({"ERROR"})
TERMINAL_CANCELLED = frozenset({"CANCEL_REQUESTED", "CANCEL_ACKNOWLEDGED"})
PROGRESS_STATUSES = frozenset({"NEW_SCRIPT", "QUEUED", "RUNNING"})

EXIT_COMPLETE = 0
EXIT_KERNEL_ERROR = 2
EXIT_CANCELLED = 3
EXIT_TIMEOUT = 4
EXIT_CONFIG = 5

# Default kernel slug: the owner is resolved from the authenticated Kaggle
# account, so a fresh repository only needs KAGGLE_API_TOKEN (ADR-067).
DEFAULT_KERNEL_SLUG = "tiny-cats-dit-slice"

DEFAULT_POLL_INTERVAL_SECONDS = 60
DEFAULT_POLL_TIMEOUT_SECONDS = 19_800  # 5.5 h — inside the 360-min job cap
DEFAULT_SESSION_TIMEOUT_SECONDS = 21_600  # 6 h kernel session cap
DEFAULT_STARTUP_GRACE_SECONDS = 120  # stale-status guard window

ENTRY_TEMPLATE = '''"""Kaggle entrypoint — generated by src/kaggle_provider.py.

The slice arguments are baked in, so the pushed kernel version pins exactly
what ran (slice target, LR horizon, experiment identity).
"""

from __future__ import annotations

import base64
import io
import os
import runpy
import shutil
import sys
import zipfile
from pathlib import Path

# Kaggle script kernels upload ONLY this file; the workspace travels embedded
# so src/, data/ and scripts/ exist inside the kernel.
WORKSPACE_B64 = {workspace!r}
HF_TOKEN_DATASET = {dataset!r}
SLICE_ARGS = {args!r}


def resolve_hf_token() -> str | None:
    """Env first, then the private dataset mount, then Kaggle Secrets."""
    token = os.environ.get("HF_TOKEN") or os.environ.get("HUGGINGFACE_TOKEN")
    if token:
        return token
    if HF_TOKEN_DATASET:
        candidate = (
            Path("/kaggle/input") / HF_TOKEN_DATASET.split("/")[-1] / "HF_TOKEN"
        )
        if candidate.is_file():
            return candidate.read_text().strip()
    try:
        from kaggle_secrets import UserSecretsClient

        return UserSecretsClient().get_secret("HF_TOKEN")
    except Exception:
        return None


def materialise_workspace() -> Path:
    """Extract the embedded workspace into Kaggle's writable output dir."""
    target = Path("/kaggle/working/slice-workspace")
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(WORKSPACE_B64))) as archive:
        archive.extractall(target)
    return target


def main() -> None:
    workspace = materialise_workspace()
    token = resolve_hf_token()
    if token:
        os.environ["HF_TOKEN"] = token
    else:
        print(
            "WARNING: no HF_TOKEN available (environment, dataset mount and "
            "Kaggle Secrets all empty) — Hub sync will degrade gracefully",
            flush=True,
        )
    sys.argv = ["train_kaggle.py", *SLICE_ARGS]
    runpy.run_path(
        str(workspace / "scripts" / "train_kaggle.py"), run_name="__main__"
    )


if __name__ == "__main__":
    main()
'''


class KaggleLaunchError(RuntimeError):
    """Raised when the kernel cannot be packaged, pushed or confirmed."""


@dataclass(frozen=True)
class KernelOutcome:
    """Terminal state of a polled kernel."""

    status: str
    failure_message: str | None = None
    elapsed_seconds: float = 0.0
    version: int | None = None


def build_slice_args(
    *,
    steps: int,
    batch_size: str | int,
    lr: str | float,
    warmup_steps: int,
    save_interval: int,
    hub_push_interval: int,
    hub_repo: str,
    experiment_id: str,
    min_lr: str | float | None = None,
    schedule_steps: int | None = None,
    hub_resume: bool = False,
    no_hub_push: bool = False,
    allow_experiment_mismatch: bool = False,
    force_download: bool = True,
) -> list[str]:
    """Arguments handed to ``scripts/train_kaggle.py`` inside the kernel.

    Mirrors the Modal launch contract (global ``--steps`` target, Hub resume,
    experiment identity, LR floor/horizon) so a slice is identical from the
    checkpoint's point of view regardless of the provider that ran it.
    """
    args: list[str] = [
        "--steps",
        str(steps),
        "--batch-size",
        str(batch_size),
        "--lr",
        str(lr),
        "--warmup-steps",
        str(warmup_steps),
        "--save-interval",
        str(save_interval),
        "--hub-push-interval",
        str(hub_push_interval),
        "--hub-repo",
        hub_repo,
        "--experiment-id",
        experiment_id,
    ]
    if min_lr is not None:
        args += ["--min-lr", str(min_lr)]
    if schedule_steps is not None:
        args += ["--schedule-steps", str(schedule_steps)]
    if hub_resume:
        args.append("--hub-resume")
    if no_hub_push:
        args.append("--no-hub-push")
    if allow_experiment_mismatch:
        args.append("--allow-experiment-mismatch")
    if force_download:
        args.append("--force-download")
    return args


def _validate_kernel_id(kernel_id: str) -> tuple[str, str]:
    parts = kernel_id.strip().split("/")
    if len(parts) != 2 or not all(parts):
        raise ValueError(
            f"kernel id must look like 'owner/slug', got {kernel_id!r} "
            "(e.g. d-oit/tiny-cats-dit-slice)"
        )
    return parts[0], parts[1]


def _kaggle_username(api: Any) -> str | None:
    """Best-effort authenticated Kaggle username from the API client.

    ``kaggle-api`` exposes it differently across versions (an attribute, a
    config getter, or the parsed ``config_values`` dict), so all three are
    tried before giving up.
    """
    direct = getattr(api, "username", None)
    if isinstance(direct, str) and direct.strip():
        return direct.strip()

    getter = getattr(api, "get_config_value", None)
    if callable(getter):
        for key in ("username", "KAGGLE_USERNAME"):
            try:
                value = getter(key)
            except Exception:  # pragma: no cover - version-specific lookup
                continue
            if isinstance(value, str) and value.strip():
                return value.strip()

    config = getattr(api, "config_values", None)
    if isinstance(config, dict):
        value = config.get("username")
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def resolve_kernel_id(api: Any, kernel_id: str | None) -> str:
    """Resolve the slice kernel ref: flag → env → authenticated account.

    Kaggle creates the kernel on first push, so a fresh repository does not
    need a pre-created kernel or a manually set repository variable: the
    owner comes from the authenticated account and the slug is fixed.

    Raises:
        KaggleLaunchError: When no owner can be resolved; the caller reports
            an actionable configuration error instead of guessing.
    """
    explicit = kernel_id or os.environ.get("KAGGLE_KERNEL_ID")
    if explicit:
        _validate_kernel_id(explicit)
        return explicit.strip()

    username = _kaggle_username(api)
    if not username:
        raise KaggleLaunchError(
            "cannot resolve the Kaggle kernel id: pass --kernel-id owner/slug "
            "or set KAGGLE_KERNEL_ID (the authenticated account did not expose "
            "a username)"
        )
    return f"{username}/{DEFAULT_KERNEL_SLUG}"


def _prepare_workspace(workspace: Path) -> None:
    if workspace.exists():
        entries = list(workspace.iterdir())
        if entries and not (workspace / KERNEL_METADATA_FILE).exists():
            raise ValueError(
                f"refusing to clear {workspace}: it is not a kernel workspace "
                f"(no {KERNEL_METADATA_FILE}); pass --workspace to a scratch dir"
            )
        for child in entries:
            if child.is_dir():
                shutil.rmtree(child)
            else:
                child.unlink()
    workspace.mkdir(parents=True, exist_ok=True)


def _workspace_b64(workspace: Path) -> str:
    """Base64 zip of everything the kernel entrypoint needs at run time."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(workspace.rglob("*")):
            if not path.is_file() or path.name in (ENTRY_FILE, KERNEL_METADATA_FILE):
                continue
            archive.write(path, path.relative_to(workspace).as_posix())
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def ensure_hf_token_dataset(api: Any, token: str) -> str:
    """Publish ``HF_TOKEN`` as a private Kaggle dataset and return its ref.

    Kaggle cannot attach secrets at kernel-push time (kaggle-api#582), so the
    documented workaround is a private dataset the kernel mounts. Creating it
    here keeps unattended slices resumable without a manual repo variable.
    """
    username = _kaggle_username(api)
    if not username:
        raise KaggleLaunchError(
            "cannot publish the HF token dataset: the authenticated account did "
            "not expose a username"
        )
    dataset_ref = f"{username}/tiny-cats-hf-token"
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp) / "tiny-cats-hf-token"
        folder.mkdir()
        (folder / "HF_TOKEN").write_text(token.strip() + "\n")
        (folder / "dataset-metadata.json").write_text(
            json.dumps(
                {
                    "title": "tiny cats hf token",
                    "id": dataset_ref,
                    "licenses": [{"name": "CC0-1.0"}],
                },
                indent=2,
            )
        )
        try:
            api.dataset_create_new(str(folder), public=False, quiet=True)
        except Exception:
            # Dataset already exists: publish a new version with the current
            # token instead of failing the launch (rotated/expired tokens are
            # the common case; see ADR-041).
            api.dataset_create_version(str(folder), "refresh HF_TOKEN", quiet=True)
    return dataset_ref


def write_kernel_metadata(
    workspace: str | Path,
    *,
    kernel_id: str,
    title: str | None = None,
    hf_token_dataset: str | None = None,
) -> Path:
    """Write ``kernel-metadata.json`` for the slice kernel."""
    _, slug = _validate_kernel_id(kernel_id)
    metadata: dict[str, Any] = {
        "id": kernel_id,
        "title": title or slug.replace("-", " "),
        "code_file": ENTRY_FILE,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [hf_token_dataset] if hf_token_dataset else [],
        "keywords": [],
    }
    path = Path(workspace) / KERNEL_METADATA_FILE
    path.write_text(json.dumps(metadata, indent=2) + "\n")
    return path


def build_kernel_workspace(
    repo_root: str | Path,
    workspace: str | Path,
    *,
    kernel_id: str,
    slice_args: list[str],
    hf_token_dataset: str | None = None,
    title: str | None = None,
) -> Path:
    """Assemble the self-contained kernel directory.

    Copies every ``src/*.py`` module plus the two scripts the entrypoint runs,
    then writes the generated entrypoint and the kernel metadata. Existing
    workspaces are rebuilt in place (a sentinel check prevents clobbering an
    unrelated directory).

    Returns:
        The workspace path, ready for ``kaggle_api.kernels_push``.
    """
    repo = Path(repo_root)
    src_dir = repo / "src"
    if not src_dir.is_dir():
        raise ValueError(f"repo root {repo} has no src/ directory")

    workspace = Path(workspace)
    _prepare_workspace(workspace)

    (workspace / "src").mkdir()
    modules = sorted(src_dir.glob("*.py"))
    if not modules:
        raise ValueError(f"no python modules found in {src_dir}")
    for module in modules:
        shutil.copy2(module, workspace / "src" / module.name)

    for relative in EXTRA_KERNEL_FILES:
        source = repo / relative
        if not source.is_file():
            raise ValueError(f"missing kernel file: {relative}")
        target = workspace / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)

    (workspace / ENTRY_FILE).write_text(
        ENTRY_TEMPLATE.format(
            workspace=_workspace_b64(workspace),
            dataset=hf_token_dataset,
            args=slice_args,
        )
    )
    write_kernel_metadata(
        workspace,
        kernel_id=kernel_id,
        title=title,
        hf_token_dataset=hf_token_dataset,
    )
    return workspace


def _load_api() -> Any:
    """Import + authenticate the Kaggle API (seam for tests)."""
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    return api


def status_name(response: Any) -> str:
    """Normalise a session-status response to a bare enum name."""
    status = getattr(response, "status", None)
    if status is None:
        status = response
    name = getattr(status, "name", None) or str(status)
    return name.rsplit(".", 1)[-1].strip().upper()


def _failure_message(response: Any) -> str | None:
    message = getattr(response, "failure_message", None) or getattr(
        response, "failureMessage", None
    )
    return str(message) if message else None


def kernel_version(api: Any, slug: str) -> int | None:
    """Latest pushed version number for ``slug``, when the API reports one."""
    try:
        entries = api.kernels_list(mine=True, search=slug) or []
    except Exception as exc:  # pragma: no cover - network shape varies
        logger.warning("could not list kernels to verify the pushed version: %s", exc)
        return None
    for meta in entries:
        ref = getattr(meta, "ref", "") or ""
        if ref.endswith("/" + slug) or getattr(meta, "slug", "") == slug:
            version = getattr(meta, "current_version_number", None)
            return int(version) if version else None
    return None


def push_kernel(
    api: Any,
    workspace: str | Path,
    *,
    session_timeout_seconds: int | None = DEFAULT_SESSION_TIMEOUT_SECONDS,
) -> dict[str, Any]:
    """Push the kernel and return ``{ref, version, url, ...}``.

    Raises :class:`KaggleLaunchError` when the server rejects sources or
    reports an error instead of queueing the run.
    """
    response = api.kernels_push(
        str(workspace),
        timeout=str(session_timeout_seconds) if session_timeout_seconds else None,
    )
    invalid_sources: list[str] = []
    for attr in (
        "invalid_dataset_sources",
        "invalid_kernel_sources",
        "invalid_model_sources",
        "invalid_competition_sources",
    ):
        invalid_sources += list(getattr(response, attr, None) or [])
    info = {
        "ref": getattr(response, "ref", None),
        "kernel_id": getattr(response, "kernel_id", None),
        "version": getattr(response, "version_number", None),
        "url": getattr(response, "url", None),
        "error": getattr(response, "error", None),
        "invalid_sources": invalid_sources,
    }
    problem = info["error"] or (
        f"invalid sources: {invalid_sources}" if invalid_sources else None
    )
    if problem:
        raise KaggleLaunchError(f"Kaggle rejected the kernel push: {problem}")
    if info["version"] is None:
        raise KaggleLaunchError(
            "Kaggle accepted the push but reported no version number; "
            "refusing to poll an unknown run"
        )
    return info


def wait_for_kernel(
    api: Any,
    kernel_id: str,
    *,
    slug: str | None = None,
    pushed_version: int | None = None,
    poll_interval_seconds: float = DEFAULT_POLL_INTERVAL_SECONDS,
    timeout_seconds: float = DEFAULT_POLL_TIMEOUT_SECONDS,
    startup_grace_seconds: float = DEFAULT_STARTUP_GRACE_SECONDS,
    clock: Callable[[], float] = time.monotonic,
    sleep: Callable[[float], None] = time.sleep,
    on_poll: Callable[[str, float], None] | None = None,
) -> KernelOutcome:
    """Poll until the *pushed* version reaches a terminal state.

    A kernel keeps its previous version's status until the new version is
    live, so an immediately-visible ``COMPLETE`` is only trusted once the
    version list reports the pushed version (or the API gives no version at
    all) — otherwise the launcher would return before training ever ran.
    """
    _, resolved_slug = _validate_kernel_id(kernel_id)
    slug = slug or resolved_slug
    start = clock()
    observed_progress = False
    while True:
        response = api.kernels_status(kernel_id)
        name = status_name(response)
        elapsed = clock() - start
        if name in PROGRESS_STATUSES:
            observed_progress = True
        if on_poll is not None:
            on_poll(name, elapsed)

        if name in TERMINAL_OK | TERMINAL_ERROR | TERMINAL_CANCELLED:
            if pushed_version is not None:
                live = kernel_version(api, slug)
                if live is not None and live < pushed_version:
                    name = ""  # stale status from the previous version
            if name:
                if (
                    name in TERMINAL_OK
                    and not observed_progress
                    and elapsed < startup_grace_seconds
                ):
                    name = ""  # too early to believe a COMPLETE we never saw run
            if name:
                return KernelOutcome(
                    status=name,
                    failure_message=_failure_message(response),
                    elapsed_seconds=elapsed,
                    version=pushed_version,
                )

        if elapsed >= timeout_seconds:
            return KernelOutcome(
                status="TIMEOUT", elapsed_seconds=elapsed, version=pushed_version
            )
        sleep(poll_interval_seconds)


def fetch_kernel_logs(
    api: Any,
    kernel_id: str,
    *,
    download_dir: str | Path,
    log_file: str | Path,
    tail_lines: int = 40,
) -> Path | None:
    """Download ``*.log`` outputs and mirror them into ``log_file``.

    Only logs are fetched: the training outputs (checkpoints) travel through
    the HF Hub, and pulling them back would move hundreds of megabytes.
    Returns the written log path, or None when no log was available.
    """
    download_dir = Path(download_dir)
    download_dir.mkdir(parents=True, exist_ok=True)
    try:
        # Kaggle treats file_pattern as a *regex*: "*.log" raises
        # "nothing to repeat at position 0" and loses the only diagnostic a
        # failed kernel leaves behind.
        api.kernels_output(
            kernel_id, path=str(download_dir), file_pattern=r".*\.log$", force=True
        )
    except Exception as exc:
        logger.warning("could not fetch kernel logs: %s", exc)
        return None

    candidates = sorted(
        download_dir.rglob("*.log"), key=lambda p: p.stat().st_mtime, reverse=True
    )
    if not candidates:
        logger.warning("kernel produced no .log output")
        return None

    newest = candidates[0]
    log_path = Path(log_file)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_bytes(newest.read_bytes())
    lines = newest.read_text(errors="replace").splitlines()
    if lines:
        print("\n".join(lines[-tail_lines:]), flush=True)
    return log_path


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Push one bounded training slice to Kaggle as a private script "
            "kernel and poll it to completion (ADR-067)"
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--target", type=int, required=True, help="Global step target")
    parser.add_argument(
        "--kernel-title", default=None, help="Kernel title (default: slug)"
    )
    parser.add_argument("--hub-repo", default="d4oit/tiny-cats-model")
    parser.add_argument("--experiment-id", default="dit-breed-conditioned-v4")
    parser.add_argument("--batch-size", default="32")
    parser.add_argument("--lr", default="5e-5")
    parser.add_argument("--warmup-steps", type=int, default=2_000)
    parser.add_argument("--save-interval", type=int, default=2_500)
    parser.add_argument("--hub-push-interval", type=int, default=5_000)
    parser.add_argument("--min-lr", default=None)
    parser.add_argument("--schedule-steps", type=int, default=None)
    parser.add_argument("--hub-resume", action="store_true")
    parser.add_argument("--no-hub-push", action="store_true")
    parser.add_argument("--allow-experiment-mismatch", action="store_true")
    parser.add_argument(
        "--hf-token-dataset",
        default=None,
        help="Private Kaggle dataset (owner/slug) holding an HF_TOKEN file",
    )
    parser.add_argument(
        "--kernel-id",
        default=None,
        help=(
            "owner/slug of the slice kernel; defaults to $KAGGLE_KERNEL_ID or "
            f"<authenticated-account>/{DEFAULT_KERNEL_SLUG}"
        ),
    )
    parser.add_argument("--no-force-download", action="store_true")
    parser.add_argument(
        "--workspace", default=".kaggle-slice", help="Kernel build directory"
    )
    parser.add_argument("--log-file", default="kaggle-training.log")
    parser.add_argument("--download-dir", default=".kaggle-output")
    parser.add_argument(
        "--session-timeout-seconds", type=int, default=DEFAULT_SESSION_TIMEOUT_SECONDS
    )
    parser.add_argument(
        "--poll-timeout-seconds", type=int, default=DEFAULT_POLL_TIMEOUT_SECONDS
    )
    parser.add_argument(
        "--poll-interval-seconds", type=int, default=DEFAULT_POLL_INTERVAL_SECONDS
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Build the kernel workspace and stop before pushing",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s | %(levelname)s | %(message)s"
    )

    repo_root = Path(__file__).resolve().parent.parent
    # Kernel id and HF-token dataset resolve from flags → env → account. The
    # control plane therefore launches Kaggle with only KAGGLE_API_TOKEN set.
    hf_token_dataset = args.hf_token_dataset or os.environ.get(
        "KAGGLE_HF_TOKEN_DATASET"
    )
    slice_args = build_slice_args(
        steps=args.target,
        batch_size=args.batch_size,
        lr=args.lr,
        warmup_steps=args.warmup_steps,
        save_interval=args.save_interval,
        hub_push_interval=args.hub_push_interval,
        hub_repo=args.hub_repo,
        experiment_id=args.experiment_id,
        min_lr=args.min_lr,
        schedule_steps=args.schedule_steps,
        hub_resume=args.hub_resume,
        no_hub_push=args.no_hub_push,
        allow_experiment_mismatch=args.allow_experiment_mismatch,
        force_download=not args.no_force_download,
    )

    kernel_id: str | None = args.kernel_id or os.environ.get("KAGGLE_KERNEL_ID")
    hf_token = os.environ.get("HF_TOKEN") or os.environ.get("HUGGINGFACE_TOKEN")
    api: Any | None = None
    if not args.dry_run and (not kernel_id or (hf_token and not hf_token_dataset)):
        # Resolving the owner / publishing the token dataset need an
        # authenticated client, which a dry run deliberately avoids touching.
        try:
            api = _load_api()
        except Exception as exc:
            logger.error("Kaggle authentication failed (%s)", exc)
            return EXIT_CONFIG
        if not kernel_id:
            try:
                kernel_id = resolve_kernel_id(api, None)
            except Exception as exc:
                logger.error("could not resolve the Kaggle kernel id (%s)", exc)
                return EXIT_CONFIG
            logger.info(
                "resolved kernel id %s from the authenticated account", kernel_id
            )
        if hf_token and not hf_token_dataset:
            try:
                hf_token_dataset = ensure_hf_token_dataset(api, hf_token)
            except Exception as exc:
                # A slice without the token cannot resume from or push to the
                # Hub, so burning GPU time on it is worse than failing here.
                logger.error("could not publish the HF token dataset (%s)", exc)
                return EXIT_CONFIG
            logger.info("HF token dataset ready: %s", hf_token_dataset)

    if not kernel_id:
        logger.error(
            "no kernel id: pass --kernel-id owner/slug or set KAGGLE_KERNEL_ID"
        )
        return EXIT_CONFIG

    try:
        workspace = build_kernel_workspace(
            repo_root,
            args.workspace,
            kernel_id=kernel_id,
            slice_args=slice_args,
            hf_token_dataset=hf_token_dataset,
            title=args.kernel_title,
        )
    except (ValueError, OSError) as exc:
        logger.error("kernel packaging failed: %s", exc)
        return EXIT_CONFIG

    logger.info("kernel workspace ready: %s", workspace)
    logger.info("slice args: %s", " ".join(slice_args))
    if args.dry_run:
        print(f"KAGGLE_DRY_RUN workspace={workspace}")
        return EXIT_COMPLETE

    if api is None:
        try:
            api = _load_api()
        except Exception as exc:
            logger.error(
                "Kaggle authentication failed (%s); set KAGGLE_API_TOKEN or "
                "~/.kaggle/access_token",
                exc,
            )
            return EXIT_CONFIG

    try:
        info = push_kernel(
            api,
            workspace,
            session_timeout_seconds=args.session_timeout_seconds,
        )
    except Exception as exc:
        logger.error("kernel push failed: %s", exc)
        return EXIT_CONFIG
    logger.info(
        "pushed %s version %s%s",
        info.get("ref") or kernel_id,
        info.get("version"),
        f" — {info['url']}" if info.get("url") else "",
    )

    outcome = wait_for_kernel(
        api,
        kernel_id,
        pushed_version=info.get("version"),
        poll_interval_seconds=args.poll_interval_seconds,
        timeout_seconds=args.poll_timeout_seconds,
        on_poll=lambda status, elapsed: logger.info(
            "kernel %s after %.0f min", status, elapsed / 60
        ),
    )
    log_path = fetch_kernel_logs(
        api,
        kernel_id,
        download_dir=args.download_dir,
        log_file=args.log_file,
    )
    summary = {
        "kernel": kernel_id,
        "version": info.get("version"),
        "status": outcome.status,
        "failure_message": outcome.failure_message,
        "elapsed_seconds": round(outcome.elapsed_seconds, 1),
        "log": str(log_path) if log_path else None,
    }
    print("KAGGLE_SLICE_JSON=" + json.dumps(summary, sort_keys=True))

    if outcome.status in TERMINAL_OK:
        logger.info("kernel COMPLETE in %.1f min", outcome.elapsed_seconds / 60)
        return EXIT_COMPLETE
    if outcome.status in TERMINAL_CANCELLED:
        logger.error(
            "kernel was cancelled after %.1f min", outcome.elapsed_seconds / 60
        )
        return EXIT_CANCELLED
    if outcome.status == "TIMEOUT":
        logger.error(
            "kernel still running after %.1f min; poll deadline reached "
            "(checkpoint should be on the Hub)",
            outcome.elapsed_seconds / 60,
        )
        return EXIT_TIMEOUT
    logger.error(
        "kernel failed after %.1f min: %s",
        outcome.elapsed_seconds / 60,
        outcome.failure_message or "no failure message",
    )
    return EXIT_KERNEL_ERROR


if __name__ == "__main__":
    sys.exit(main())
